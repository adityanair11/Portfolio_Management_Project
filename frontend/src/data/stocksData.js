// Helper function to search stocks
export const searchStocks = (query) => {
  if (!query || query.trim() === '') return stocksData;
  
  const searchTerm = query.toLowerCase();
  return stocksData.filter(stock => 
    stock.symbol.toLowerCase().includes(searchTerm) ||
    stock.name.toLowerCase().includes(searchTerm) ||
    stock.sector.toLowerCase().includes(searchTerm)
  );
};

// Helper function to get stock by symbol
export const getStockBySymbol = (symbol) => {
  return stocksData.find(stock => stock.symbol === symbol);
};

// Helper function to get stocks by market
export const getStocksByMarket = (market) => {
  return stocksData.filter(stock => stock.market === market);
};

// Helper function to get stocks by currency
export const getStocksByCurrency = (currency) => {
  return stocksData.filter(stock => stock.currency === currency);
};
